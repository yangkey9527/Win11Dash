import random

_ALL = WORKDAY_QUOTES + WEEKEND_QUOTES
_MIN_POOL = 8    # 去重窗口：最近 N 句不再复


def pick_quote(is_workday, recent=None):
    """从工作日/休息日池随机挑一句，recent(最近 8 句) 里排除。
    返回 (quote, is_workday) 用于调用方记录。"""
    pool = WORKDAY_QUOTES if is_workday else WEEKEND_QUOTES
    if recent is None:
        recent = set()
    eligible = [q for q in pool if q not in recent]
    if not eligible:
        # 极端情况池子耗竭（理论上不会），退化为全池随机
        eligible = pool
    q = random.choice(eligible)
    return q
